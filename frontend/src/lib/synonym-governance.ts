export type CategoriaTermoNaoMolecular = 'classe_terapeutica' | 'indicacao_clinica' | 'sintoma' | 'termo_generico';

/** Mesma normalização usada na auditoria: minúsculas, sem acento, sem ®/™, pontuação → espaço. */
export function normalizarTermo(s: string): string {
  return s.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase()
    .replace(/[®™]/g, '').replace(/[+/\-_.,()]/g, ' ').replace(/\s+/g, ' ').trim();
}

